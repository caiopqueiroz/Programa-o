# include <stdio.h>

// Usando caracteres de escape
int main() {
    // Som de alerta
    printf("\a");

    // Backspace
    printf("\b");

    // Tabulação horizontal
    printf("\tTeste\n");

    printf("Ola mundo\n");
    printf("Ola\nMundo\n");
    printf("Ola\tMundo\n");
    printf("\"Ola Mundo\"\n");

    return 0;
}
